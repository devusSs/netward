// Package tlscert provides the TLS certificate of netward's web interface.
//
// A [Manager] loads the certificate and key from PEM files. When neither file
// exists it creates a self-signed certificate there, like Pi-hole does, so
// HTTPS works without any setup. Browsers show a warning for it once, because
// no trusted authority signed it.
//
// Certificates netward generated itself are replaced automatically 30 days
// before they expire and whenever they no longer cover the host's names and
// private addresses, for example after its address changed. Certificates
// provided by the user are never modified.
package tlscert

import (
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/sha256"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/hex"
	"encoding/pem"
	"errors"
	"fmt"
	"io/fs"
	"log/slog"
	"math/big"
	"net"
	"net/netip"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"sync"
	"time"
)

const (
	// validity stays within the 397 days browsers accept for server
	// certificates.
	validity    = 397 * 24 * time.Hour
	renewBefore = 30 * 24 * time.Hour
	// backdate tolerates clocks of clients that are slightly behind.
	backdate = time.Hour

	organization = "netward"
	commonName   = "netward self-signed certificate"
	serialBits   = 128

	certPerm = 0o644
	keyPerm  = 0o600
)

// Config configures a [Manager].
type Config struct {
	// CertFile is the path of the PEM-encoded certificate (chain).
	CertFile string
	// KeyFile is the path of the PEM-encoded private key.
	KeyFile string
	// Hosts are extra host names or IP addresses a generated certificate
	// covers, in addition to the host name, localhost, the loopback
	// addresses and the host's private addresses.
	Hosts []string
	// Logger receives the manager's logs. Nil discards them.
	Logger *slog.Logger
}

// deps are the parts of the system a [Manager] depends on. Tests replace
// them.
type deps struct {
	now      func() time.Time
	hostname func() (string, error)
	addrs    func() ([]net.Addr, error)
}

// Manager provides the TLS certificate. It is safe for concurrent use.
type Manager struct {
	certFile string
	keyFile  string
	extra    []string
	logger   *slog.Logger
	deps     deps

	mu        sync.Mutex
	cert      *tls.Certificate
	generated bool
}

// New loads the certificate, creating a self-signed one if neither file
// exists or replacing a generated one that is about to expire or misses a
// host. It fails if only one of the files exists or they cannot be read.
func New(cfg Config) (*Manager, error) {
	return newManager(cfg, deps{now: time.Now, hostname: os.Hostname, addrs: net.InterfaceAddrs})
}

func newManager(cfg Config, d deps) (*Manager, error) {
	if cfg.CertFile == "" || cfg.KeyFile == "" {
		return nil, errors.New("certificate and key file are required")
	}

	logger := cfg.Logger
	if logger == nil {
		logger = slog.New(slog.DiscardHandler)
	}

	m := &Manager{
		certFile:  cfg.CertFile,
		keyFile:   cfg.KeyFile,
		extra:     slices.Clone(cfg.Hosts),
		logger:    logger.With(slog.String("component", "tlscert")),
		deps:      d,
		mu:        sync.Mutex{},
		cert:      nil,
		generated: false,
	}

	err := m.load()
	if err != nil {
		return nil, err
	}

	return m, nil
}

// GetCertificate returns the current certificate. It suits
// [tls.Config.GetCertificate]. A generated certificate that is about to
// expire or misses a host is replaced first; if that fails, the old one is
// returned and the error is logged.
func (m *Manager) GetCertificate(*tls.ClientHelloInfo) (*tls.Certificate, error) {
	m.mu.Lock()
	defer m.mu.Unlock()

	if m.generated {
		reason := m.renewalReason(m.cert.Leaf)
		if reason != "" {
			err := m.generate(reason)
			if err != nil {
				m.logger.Error("renewing tls certificate failed", slog.Any("error", err))
			}
		}
	}

	return m.cert, nil
}

// Generated reports whether the current certificate was generated by
// netward.
func (m *Manager) Generated() bool {
	m.mu.Lock()
	defer m.mu.Unlock()

	return m.generated
}

func (m *Manager) load() error {
	m.mu.Lock()
	defer m.mu.Unlock()

	certExists, err := exists(m.certFile)
	if err != nil {
		return err
	}

	keyExists, err := exists(m.keyFile)
	if err != nil {
		return err
	}

	switch {
	case !certExists && !keyExists:
		return m.generate("no certificate yet")
	case certExists != keyExists:
		return fmt.Errorf("found only one of %s and %s; provide both or remove the other to generate a "+
			"self-signed certificate", m.certFile, m.keyFile)
	}

	cert, err := tls.LoadX509KeyPair(m.certFile, m.keyFile)
	if err != nil {
		return fmt.Errorf("load tls certificate: %w", err)
	}

	m.cert = &cert
	m.generated = isGenerated(cert.Leaf)

	if m.generated {
		reason := m.renewalReason(cert.Leaf)
		if reason != "" {
			return m.generate(reason)
		}
	}

	m.logLoaded(cert.Leaf)

	return nil
}

func (m *Manager) logLoaded(leaf *x509.Certificate) {
	attrs := []any{
		slog.String("cert", m.certFile),
		slog.Bool("self_signed", m.generated),
		slog.Time("not_after", leaf.NotAfter),
		slog.String("sha256", fingerprint(leaf)),
	}

	now := m.deps.now()

	switch {
	case !now.Before(leaf.NotAfter):
		m.logger.Warn("tls certificate has expired", attrs...)
	case leaf.NotAfter.Sub(now) < renewBefore:
		m.logger.Warn("tls certificate expires soon", attrs...)
	default:
		m.logger.Info("tls certificate loaded", attrs...)
	}
}

// renewalReason returns why a generated certificate must be replaced, or ""
// if it can stay.
func (m *Manager) renewalReason(leaf *x509.Certificate) string {
	if leaf.NotAfter.Sub(m.deps.now()) < renewBefore {
		return "certificate expires soon"
	}

	ips, names := m.hosts()

	for _, ip := range ips {
		if !slices.ContainsFunc(leaf.IPAddresses, func(have net.IP) bool { return have.Equal(ip.AsSlice()) }) {
			return "certificate does not cover " + ip.String()
		}
	}

	for _, name := range names {
		if !slices.Contains(leaf.DNSNames, name) {
			return "certificate does not cover " + name
		}
	}

	return ""
}

// hosts returns the addresses and names a generated certificate must cover.
func (m *Manager) hosts() ([]netip.Addr, []string) {
	ips := []netip.Addr{netip.IPv6Loopback(), netip.MustParseAddr("127.0.0.1")}
	names := []string{"localhost"}

	hostname, err := m.deps.hostname()
	if err == nil && hostname != "" {
		names = append(names, strings.ToLower(hostname))
	}

	addrs, err := m.deps.addrs()
	if err != nil {
		m.logger.Warn("listing interface addresses for tls certificate failed", slog.Any("error", err))
	}

	for _, a := range addrs {
		ipNet, ok := a.(*net.IPNet)
		if !ok {
			continue
		}

		addr, ok := netip.AddrFromSlice(ipNet.IP)
		if ok && addr.Unmap().IsPrivate() {
			ips = append(ips, addr.Unmap())
		}
	}

	for _, host := range m.extra {
		addr, parseErr := netip.ParseAddr(host)
		if parseErr == nil {
			ips = append(ips, addr.Unmap())
		} else {
			names = append(names, strings.ToLower(host))
		}
	}

	slices.SortFunc(ips, netip.Addr.Compare)
	slices.Sort(names)

	return slices.Compact(ips), slices.Compact(names)
}

// generate creates a self-signed certificate, writes it and its key and
// makes it the current one. The caller must hold m.mu.
func (m *Manager) generate(reason string) error {
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return fmt.Errorf("generate key: %w", err)
	}

	serial, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), serialBits))
	if err != nil {
		return fmt.Errorf("generate serial number: %w", err)
	}

	ips, names := m.hosts()
	now := m.deps.now()

	var subject pkix.Name
	subject.Organization = []string{organization}
	subject.CommonName = commonName

	var template x509.Certificate
	template.SerialNumber = serial
	template.Subject = subject
	template.NotBefore = now.Add(-backdate)
	template.NotAfter = now.Add(validity)
	template.KeyUsage = x509.KeyUsageDigitalSignature
	template.ExtKeyUsage = []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth}
	template.BasicConstraintsValid = true
	template.DNSNames = names

	for _, ip := range ips {
		template.IPAddresses = append(template.IPAddresses, ip.AsSlice())
	}

	der, err := x509.CreateCertificate(rand.Reader, &template, &template, &key.PublicKey, key)
	if err != nil {
		return fmt.Errorf("create certificate: %w", err)
	}

	keyDER, err := x509.MarshalPKCS8PrivateKey(key)
	if err != nil {
		return fmt.Errorf("encode key: %w", err)
	}

	certPEM := pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Headers: nil, Bytes: der})
	keyPEM := pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Headers: nil, Bytes: keyDER})

	// Write the key first: a certificate without its key would make the
	// next start fail instead of generating a new pair.
	err = writeFile(m.keyFile, keyPEM, keyPerm)
	if err == nil {
		err = writeFile(m.certFile, certPEM, certPerm)
	}

	if err != nil {
		return err
	}

	cert, err := tls.X509KeyPair(certPEM, keyPEM)
	if err != nil {
		return fmt.Errorf("load generated certificate: %w", err)
	}

	m.cert = &cert
	m.generated = true

	m.logger.Info("self-signed tls certificate generated",
		slog.String("reason", reason),
		slog.String("cert", m.certFile),
		slog.Any("names", names),
		slog.Any("ips", ips),
		slog.Time("not_after", cert.Leaf.NotAfter),
		slog.String("sha256", fingerprint(cert.Leaf)),
	)

	return nil
}

// isGenerated reports whether leaf is a self-signed certificate created by
// netward.
func isGenerated(leaf *x509.Certificate) bool {
	return leaf.Subject.CommonName == commonName &&
		slices.Equal(leaf.Subject.Organization, []string{organization}) &&
		// CheckSignatureFrom would also require leaf to be a CA.
		leaf.CheckSignature(leaf.SignatureAlgorithm, leaf.RawTBSCertificate, leaf.Signature) == nil
}

// fingerprint returns the SHA-256 fingerprint of leaf as browsers show it.
func fingerprint(leaf *x509.Certificate) string {
	sum := sha256.Sum256(leaf.Raw)

	return strings.ToUpper(hex.EncodeToString(sum[:]))
}

func exists(path string) (bool, error) {
	_, err := os.Stat(path)

	switch {
	case err == nil:
		return true, nil
	case errors.Is(err, fs.ErrNotExist):
		return false, nil
	default:
		return false, fmt.Errorf("check %s: %w", path, err)
	}
}

// writeFile replaces path atomically, so a crash never leaves half a file.
func writeFile(path string, data []byte, perm os.FileMode) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".*")
	if err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}

	defer func() { _ = os.Remove(tmp.Name()) }()

	_, err = tmp.Write(data)
	if err == nil {
		err = tmp.Chmod(perm)
	}

	closeErr := tmp.Close()
	if err == nil {
		err = closeErr
	}

	if err == nil {
		err = os.Rename(tmp.Name(), path)
	}

	if err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}

	return nil
}
